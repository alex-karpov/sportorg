CARGO_LOCK = """# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "heck"
version = "0.5.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "abc"

[[package]]
name = "local-ext"
version = "0.1.0"
dependencies = [
 "heck",
 "pyo3 0.28.3",
]

[[package]]
name = "pyo3"
version = "0.28.3"
source = "registry+https://github.com/rust-lang/crates.io-index"
"""


def test_parse_cargo_lock() -> None:
    packages = d.parse_cargo_lock(CARGO_LOCK)
    assert [(p.name, p.version, p.line) for p in packages] == [
        ("heck", "0.5.0", 5),
        ("local-ext", "0.1.0", 11),
        ("pyo3", "0.28.3", 19),
    ]
    assert packages[0].is_registry
    assert not packages[1].is_registry
    assert packages[1].dependencies == ("heck", "pyo3 0.28.3")
    assert packages[2].dependencies == ()


def test_runtime_dev_split_with_markers() -> None:
    lock = d.parse_uv_lock(UV_LOCK)
    assert lock.root.name == "demo"
    reach = d.classify(lock)
    assert set(reach) == {
        ("a", "1.0"),
        ("a", "2.0"),
        ("b", "3.0"),
        ("c", "4.0"),
        ("d", "5.0"),
        ("e", "0.5"),
        ("f", "6.0"),
    }
    assert reach["a", "1.0"].groups == ("runtime",)
    assert reach["a", "1.0"].py38_only
    assert not reach["a", "2.0"].py38_only
    assert reach["e", "0.5"].py38_only  # only through a 1.0 and a Python 3.8 edge
    assert reach["b", "3.0"].klass == "runtime"
    assert reach["c", "4.0"].groups == ("extra:gui",)
    assert reach["c", "4.0"].klass == "extra"
    assert reach["d", "5.0"].groups == ("dev:dev",)
    assert reach["d", "5.0"].klass == "dev"
    assert reach["f", "6.0"].groups == ("dev:dev", "runtime")
    assert reach["f", "6.0"].klass == "runtime"


def test_split_differs_from_check_licenses_on_multi_version_names() -> None:
    lock = d.parse_uv_lock(UV_LOCK)
    runtime, dev = d.split_by_name(UV_LOCK, lock.root.name)
    # check_licenses keeps one dependency list per name (the last version's): "e" is lost
    assert runtime == ["a", "b", "f"]
    assert dev == ["c", "d", "e"]
    assert d.runtime_names(d.classify(lock)) == ["a", "b", "e", "f"]


def test_package_lines_point_at_name_entries() -> None:
    lock = d.parse_uv_lock(UV_LOCK)
    lines = UV_LOCK.splitlines()
    for package in lock.packages:
        assert lines[package.line - 1] == f'name = "{package.name}"'
        assert lines[package.line] == f'version = "{package.version}"'


def test_parse_requirement_and_direct_lines() -> None:
    pyproject = (
        "[project]\n"
        'dependencies = [\n  "orjson>=3.9.5,<4",\n  "x>=5; python_version < \'3.9\'",\n]\n'
        "[project.optional-dependencies]\n"
        'gui = [\n  "PySide6>=6,<7",\n]\n'
        "[dependency-groups]\n"
        'dev = [\n  "pytest-cov",\n  "x>=5; python_version < \'3.9\'",\n]\n'
    )
    req = d.parse_requirement("x[extra]>=5; python_version < '3.9'")
    assert (req.name, req.spec, req.marker) == ("x", ">=5", "python_version < '3.9'")
    rows = d.direct_dependencies(pyproject)
    assert [(r.section, r.name, r.line) for r in rows] == [
        ("dependencies", "orjson", 3),
        ("dependencies", "x", 4),
        ("extra:gui", "pyside6", 8),
        ("dev:dev", "pytest-cov", 12),
        ("dev:dev", "x", 13),
    ]
    assert rows[1].marker == "python_version < '3.9'"
    assert rows[1].py38_only
    assert not rows[0].py38_only
    assert rows[2].raw == "PySide6>=6,<7"


def test_licence_priority_and_verdict() -> None:
    expr = d.licence_of("MIT OR Apache-2.0", [], None)
    assert (expr.source, expr.spdx, expr.verdict) == ("expression", "MIT OR Apache-2.0", "ok")
    classifier = d.licence_of(
        None, ["License :: OSI Approved :: MIT License", "Topic :: Utilities"], "ignored"
    )
    assert (classifier.source, classifier.spdx, classifier.verdict) == ("classifier", "MIT", "ok")
    free = d.licence_of("", [], "GPL-2.0-only")
    assert (free.source, free.verdict) == ("free text", "problem")
    unknown = d.licence_of(None, [], "see LICENSE file\nmore")
    assert (unknown.source, unknown.spdx, unknown.verdict) == (
        "free text",
        "see LICENSE file",
        "unknown",
    )
    none = d.licence_of(None, [], "UNKNOWN")
    assert (none.source, none.spdx, none.verdict) == ("not declared", "", "unknown")


def test_crates_licence_slash_is_or() -> None:
    assert d.crate_licence("MIT/Apache-2.0").spdx == "MIT OR Apache-2.0"
    assert d.crate_licence("MIT/Apache-2.0").verdict == "ok"
    assert d.crate_licence(None).source == "not declared"


