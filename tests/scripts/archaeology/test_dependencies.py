def test_osv_fixed_versions_and_aliases() -> None:
    vulns = d.parse_osv(OSV_RESPONSE, "pkg")
    assert [v.id for v in vulns] == ["GHSA-w", "PYSEC-1"]  # sorted by id
    first = vulns[1]
    assert first.aliases == ("CVE-1", "GHSA-x")
    assert first.fixed == ("2.1", "3.2")
    assert first.severity == (("CVSS_V3", "CVSS:3.1/AV:N"),)
    assert first.label == "HIGH"
    assert vulns[0].withdrawn
    assert vulns[0].fixed == ()
    assert vulns[0].label == ""
    assert d.parse_osv({}, "pkg") == []


def test_crosscheck_matches_on_aliases() -> None:
    key = ("PyPI", "a", "1.0")
    own: dict[d.PkgKey, list[d.Finding]] = {
        key: [
            d.Finding("PYSEC-1", ("CVE-1", "GHSA-x")),
            d.Finding("GHSA-own", ()),
            d.Finding("GHSA-w", (), withdrawn=True),
        ]
    }
    other: dict[d.PkgKey, list[d.Finding]] = {
        key: [d.Finding("GHSA-x", ("CVE-1",)), d.Finding("GHSA-other", ())]
    }
    rows = d.crosscheck(own, other)
    assert [(r.status, r.id) for r in rows] == [
        ("only_other", "GHSA-other"),
        ("only_own", "GHSA-own"),
        ("only_own", "GHSA-w"),
        ("both", "PYSEC-1"),
    ]
    by_id = {r.id: r for r in rows}
    assert by_id["PYSEC-1"].matched == ("GHSA-x",)
    assert by_id["GHSA-w"].reason == "withdrawn in own record"
    assert d.count_status(rows) == {"both": 1, "only_own": 2, "only_other": 1}


def test_crosscheck_other_version_reason() -> None:
    own = {
        ("PyPI", "a", "1.0"): [],
        ("PyPI", "a", "2.0"): [d.Finding("GHSA-v", ())],
    }
    other = {("PyPI", "a", "1.0"): [d.Finding("GHSA-v", ())]}
    rows = d.crosscheck(own, other)
    assert [(r.status, r.version, r.reason) for r in rows] == [
        ("only_other", "1.0", "own lists it for version 2.0 of the same package"),
        ("only_own", "2.0", "the other side reports it for version 1.0 of the same package"),
    ]


