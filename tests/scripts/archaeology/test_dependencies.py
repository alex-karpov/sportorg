def _sha(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()


def test_combined_digest_and_missing_cache(tmp_path: Path) -> None:
    for key, body in (("a==1", "{}"), ("b==2", '{"info": {}}')):
        target = fetch.cache_path(tmp_path, "pypi", key)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(body, encoding="utf-8")
    cache = d.Cache(tmp_path)
    assert cache.load("pypi", "a==1") == {}
    assert cache.load("pypi", "zzz==9") is None
    assert cache.missing == ["pypi/zzz==9"]
    assert list(cache.of_kind("pypi")) == ["pypi/a==1"]
    cache.load("pypi", "b==2")
    shas = sorted([_sha("{}"), _sha('{"info": {}}')])
    assert cache.combined("pypi") == _sha("\n".join(shas))
    assert cache.of_kind("osv") == {}


def test_run_is_deterministic_and_has_no_personal_fields(tmp_path: Path) -> None:
    cache_dir = tmp_path / "cache"
    pypi: Json = {
        "info": {
            "license_expression": "MIT",
            "classifiers": [],
            "author": "Some Person",
            "author_email": "p@example.org",
        },
        "urls": [{"upload_time_iso_8601": "2020-01-02T00:00:00Z"}],
    }
    keys: dict[tuple[str, str], Json] = {
        ("pypi", f"{n}=={v}"): pypi
        for n, v in (("a", "1.0"), ("a", "2.0"), ("b", "3.0"), ("c", "4.0"), ("d", "5.0"))
    }
    keys |= {("pypi", "e==0.5"): pypi, ("pypi", "f==6.0"): pypi}
    for (kind, key), body in keys.items():
        target = fetch.cache_path(cache_dir, kind, key)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(json.dumps(body), encoding="utf-8")
    tools = d.ToolOutputs(
        uv_audit=d.ToolFile("uv-audit-legacy.json", "0" * 64, {"vulnerabilities": []}),
        osv_scanner=d.ToolFile("osv-scanner-legacy.json", "1" * 64, {"results": []}),
    )
    inputs = d.Inputs(
        uv_lock=UV_LOCK,
        pyproject='[project]\ndependencies = [\n  "b>=1",\n]\n',
        cargo_lock=CARGO_LOCK,
        tools=tools,
    )
    one, two = tmp_path / "one", tmp_path / "two"
    d.run(inputs, cache_dir, one)
    d.run(inputs, cache_dir, two)
    names = sorted(p.name for p in one.iterdir())
    assert "summary.json" in names
    assert "crosscheck.md" in names
    for name in names:
        assert (one / name).read_bytes() == (two / name).read_bytes()
    text = "".join((one / name).read_text(encoding="utf-8") for name in names)
    assert "Some Person" not in text
    assert "example.org" not in text
    summary = as_dict(parse_json((one / "summary.json").read_text(encoding="utf-8")))
    assert as_dict(summary["python"])["packages"] == {"runtime": 5, "extra": 1, "dev": 1}
    assert Loc("pysport", "uv.lock", 6).tag() in (one / "python-packages.md").read_text("utf-8")
